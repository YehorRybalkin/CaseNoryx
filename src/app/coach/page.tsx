import type { Metadata } from "next";
import { CasePicker } from "@/components/cases/case-picker";
import { CoachChat } from "@/components/coach/coach-chat";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Callout, PageHeader } from "@/components/ui/misc";
import { COACH_MODES, COACH_MODE_LABELS } from "@/lib/coach";
import { CASES, caseSummaries, getCase } from "@/lib/cases/registry";
import { aiConfigured } from "@/server/env";
import { getSettings, listHypotheses } from "@/server/services";

export const metadata: Metadata = { title: "AI Consulting Coach" };

export default async function CoachPage({ searchParams }: { searchParams: Promise<{ case?: string }> }) {
  const { case: c } = await searchParams;
  const def = getCase(c ?? "") ?? CASES[0];
  const [settings, hyps] = await Promise.all([getSettings(), listHypotheses(def.slug)]);
  const ai = aiConfigured() && settings.aiCoachEnabled;
  return (
    <div>
      <PageHeader eyebrow="AI Consulting Coach" title="Your Socratic case mentor" description="The coach challenges your reasoning, points you to the right analyses and explains methods — without handing you the answer." />
      <div className="grid gap-4 lg:grid-cols-3">
        <div className="space-y-4">
          <CasePicker cases={caseSummaries()} value={def.slug} />
          <Card>
            <CardHeader><CardTitle>Status</CardTitle></CardHeader>
            <CardContent className="space-y-2 text-sm">
              <div className="flex items-center gap-2">{ai ? <Badge variant="success">AI coach active</Badge> : <Badge variant="warning">Offline hints</Badge>}</div>
              <p className="text-xs text-muted-foreground">{ai ? "Replies are generated by Claude via the server. Your API key never leaves the server." : aiConfigured() ? "AI coaching is turned off in Settings. You receive case-specific offline hints." : "No ANTHROPIC_API_KEY is configured. You receive case-specific offline hints that escalate as you ask."}</p>
            </CardContent>
          </Card>
          <Card>
            <CardHeader><CardTitle>Modes</CardTitle></CardHeader>
            <CardContent className="space-y-2">{COACH_MODES.map((m) => <div key={m} className="text-sm"><span className="font-medium">{COACH_MODE_LABELS[m].label}:</span> <span className="text-muted-foreground">{COACH_MODE_LABELS[m].description}</span></div>)}</CardContent>
          </Card>
          <Callout>The coach cannot change grades, submissions or answer keys. Your hypotheses for this case are shared with it as context.</Callout>
        </div>
        <Card className="lg:col-span-2">
          <CardContent className="pt-5">
            <CoachChat key={def.slug} caseSlug={def.slug} caseTitle={def.title} defaultMode={settings.coachMode} context={{ activeTab: "coach", hypotheses: hyps.map((h) => h.title) }} className="h-[640px]" />
          </CardContent>
        </Card>
      </div>
    </div>
  );
}
